/**
 * Cuts the navbar copy of the wordmark from the drawn one.
 *
 * `kladde_spec.svg` is drawn at poster size: its 1.3 strokes come out under a pixel in the navbar
 * label and wash out. This scales every stroke measure by one factor so the lines hold at that
 * size — stroke-dasharray and stroke-dashoffset along with stroke-width, because a dash pattern
 * left at its drawn length turns to blobs under a thicker stroke.
 *
 * The result is generated, not drawn. Redraw static/img/kladde_spec.svg and run this again; never
 * edit the navbar cut by hand.
 *
 * Run it with: npm run wordmark
 */
import fs from 'node:fs';
import path from 'node:path';

const SOURCE = path.join('static', 'img', 'kladde_spec.svg');
const TARGET = path.join('static', 'img', 'kladde_spec_navbar.svg');

// Judged against the drawing at navbar size: enough to hold the lines, not so much that the
// dotted letters close into blocks. It follows the drawing, so try a few after redrawing —
// `F=1.2 npm run wordmark` writes the cut at that factor instead.
const FACTOR = Number(process.env.F ?? 1.4);

const MEASURES = ['stroke-width', 'stroke-dasharray', 'stroke-dashoffset'];

/** Every number in a declaration, scaled; `none` and other keywords pass through untouched. */
function scaleMeasure(value) {
  if (value.trim() === 'none') return value;
  return value.replace(/\d*\.?\d+/g, (number) => String(Number((number * FACTOR).toFixed(5))));
}

const note = `<!-- Navbar cut of ${path.basename(SOURCE)}: every stroke measure scaled by ${FACTOR}, so the
     lines hold at navbar size. Generated by scripts/thicken-wordmark.mjs, not drawn: redraw the
     source and run \`npm run wordmark\` again, never edit this file by hand. -->\n`;

let svg = fs.readFileSync(SOURCE, 'utf8');
const counts = [];
for (const measure of MEASURES) {
  const pattern = new RegExp(`${measure}:([^;"]*)`, 'g');
  counts.push(`${measure} ×${(svg.match(pattern) ?? []).length}`);
  svg = svg.replace(pattern, (_, value) => `${measure}:${scaleMeasure(value)}`);
}
fs.writeFileSync(TARGET, svg.replace('<svg\n', `${note}<svg\n`));

console.log(`${TARGET}: scaled by ${FACTOR} (${counts.join(', ')})`);
